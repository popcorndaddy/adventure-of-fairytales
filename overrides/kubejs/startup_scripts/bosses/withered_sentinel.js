// the armour is thousands of years old: now and then a tiny breath of dust and smoke escapes a joint
const WS_JOINTS = [[0, 66, 0], [18, 60, 2], [-18, 60, 2], [16, 44, -2], [-16, 44, -2], [9, 36, 0], [-9, 36, 0], [7, 22, -3], [-7, 22, -3]]
function fxArmorBreath(e, strength) {
  let j = WS_JOINTS[Math.floor(Math.random() * WS_JOINTS.length)]
  let q = wsLocal(e, j[0], j[1], j[2])
  wsAt(e, q, `particle minecraft:smoke ~ ~ ~ 0.06 0.04 0.06 0.008 ${Math.max(1, Math.round(2 * strength))} force`)
  wsAt(e, q, `particle minecraft:white_ash ~ ~ ~ 0.12 0.08 0.12 0.01 ${Math.max(1, Math.round(3 * strength))} force`)
  if (Math.random() < 0.15) wsAt(e, q, 'playsound minecraft:block.fire.extinguish hostile @a ~ ~ ~ 0.12 0.55')
}

// heavy armoured footsteps while he walks: a deep step, a plate clank and chain mail, on each foot strike
// (the walk cycle is 48 ticks with a strike every 24, alternating feet)
function wsFootsteps(e, d, act) {
  let sp = 0
  try { let v = wsVec(e.getDeltaMovement()); if (v) sp = Math.sqrt(v.x * v.x + v.z * v.z) } catch (err) {}
  if (act != '' || sp < 0.015) { d.putInt('ws_step', 0); return }
  let n = d.getInt('ws_step') + 1
  d.putInt('ws_step', n)
  if (n % 24 != 4) return
  let q = wsLocal(e, (Math.floor(n / 24) % 2 == 0) ? -7 : 7, 0, 2)
  wsAt(e, q, 'playsound minecraft:entity.iron_golem.step hostile @a ~ ~ ~ 1.6 0.55')
  wsAt(e, q, 'playsound minecraft:item.armor.equip_netherite hostile @a ~ ~ ~ 1.0 0.6')
  wsAt(e, q, 'playsound minecraft:block.chain.step hostile @a ~ ~ ~ 0.9 0.7')
  if (Math.random() < 0.5) wsAt(e, q, 'playsound minecraft:item.armor.equip_iron hostile @a ~ ~ ~ 0.7 0.5')
  fxDust(e, q, WS_DARK, 1.0, 0.25, 3, 0.01)
}

// ------------------------------------------------------------------ the fight
global.wsTick = e => {
  let d = e.persistentData
  if (!d.contains('ws_init')) {
    d.putBoolean('ws_init', true)
    d.putInt('cd_sweep', 20); d.putInt('cd_push', 120); d.putInt('cd_summon', 300); d.putInt('cd_stomp', 60); d.putInt('cd_dash', 160)
  }
  if (e.tickCount % 5 == 0) wsBar(e)
  ;['cd_sweep', 'cd_push', 'cd_summon', 'cd_stomp', 'cd_dash'].forEach(k => { if (d.getInt(k) > 0) d.putInt(k, d.getInt(k) - 1) })
  let target = e.getTarget()
  let act = d.getString('ws_act'), t = d.getInt('ws_t')
  let p2 = e.getHealth() <= e.getMaxHealth() * 0.5

  // ---- dormant: kneeling on his sword until a player comes close (or hits him)
  if (!d.getBoolean('ws_awake') && act != 'awaken') {
    e.getNavigation().stop(); e.setAggressive(false)
    if (e.tickCount % 40 == 0) { fxHeart(e, 0.4); fxGoldPulse(e, 0.35) }
    if (Math.random() < 0.006) fxArmorBreath(e, 0.6)
    let wake = false
    e.server.players.forEach(p => { if (!p.isCreative() && !p.isSpectator() && p.level == e.level && wsDist(p, e) < 16) wake = true })
    if (wake || target) { d.putBoolean('ws_guarded', true); wsStart(e, 'awaken') }
    return
  }
  e.setAggressive(!!target)

  // ---- ambient magic: faint runes near the shoulders, pixels rising from his boots, the heart breathing light
  if (act == '' && e.tickCount % 23 == 0) fxRunes(e, wsLocal(e, (Math.random() < 0.5 ? -1 : 1) * 16, 62, 0), 0.4, 3)
  if (act == '' && e.tickCount % 31 == 0) fxDust(e, wsLocal(e, (Math.random() - 0.5) * 16, 2, -2), WS_DARK, 1.2, 0.35, 3, 0.01)
  if (e.tickCount % (target ? 12 : 30) == 0) { fxHeart(e, target ? 1.0 : 0.5); fxGoldPulse(e, target ? 1.0 : 0.55) }
  wsFootsteps(e, d, act)
  if (Math.random() < 0.022) fxArmorBreath(e, 1.0)                    // about once every 2-3 seconds

  if (act != '') {
    d.putInt('ws_t', t + 1)
    let E = wsEv()[act == 'summon_hold' ? 'summon_start' : act] || {}
    if ((E.heart || []).indexOf(t) >= 0) fxHeart(e, 1.8)                 // heart surges marked in the animation
    if (act == 'awaken') {
      // dormant -> fingers tighten (stir) -> rises (rise), draws the sword (draw) -> guard -> heart flare (flare)
      if (t == 2) wsCmd(e, 'playsound minecraft:block.respawn_anchor.charge hostile @a ~ ~ ~ 3 0.5')
      if (t >= E.runes[0] && t < E.runes[1] && t % 3 == 0) {           // runes and cubes stream into his heart
        let a = t * 0.4, q = wsLocal(e, Math.cos(a) * 30, 30 + (t % 30), Math.sin(a) * 30)
        fxRunes(e, q, 0.3, 4); fxDust(e, q, WS_DARK, 1.4, 0.2, 2, 0)
      }
      // deep war horns: the raid horn and a goat horn played at half speed sound like a huge Viking horn
      if (t == E.stir) { wsCmd(e, 'playsound minecraft:event.raid.horn hostile @a ~ ~ ~ 4 0.5'); wsCmd(e, 'playsound minecraft:item.goat_horn.sound.6 hostile @a ~ ~ ~ 3 0.5') }
      if (t == E.stir + 14) wsCmd(e, 'playsound minecraft:item.goat_horn.sound.7 hostile @a ~ ~ ~ 2.5 0.5')
      if (t == E.stir) { let v = wsLocal(e, 0, 72, -6); wsAt(e, v, 'particle minecraft:smoke ~ ~ ~ 0.15 0.05 0.15 0.02 6 force'); wsAt(e, v, 'particle minecraft:white_ash ~ ~ ~ 0.3 0.1 0.3 0.02 8 force') }
      if (t >= E.rise && t <= E.rise + 24 && t % 3 == 0) fxArmorBreath(e, 1.6)   // centuries of dust shaken off
      if (t == E.rise) { wsCmd(e, 'playsound minecraft:entity.warden.emerge hostile @a ~ ~ ~ 3 0.7'); wsCmd(e, 'playsound minecraft:event.raid.horn hostile @a ~ ~ ~ 4 0.56') }
      if (t == E.flare - 2) wsCmd(e, 'playsound minecraft:item.goat_horn.sound.3 hostile @a ~ ~ ~ 3 0.5')
      if (t == E.draw) { wsAt(e, wsLocal(e, -2, 1, 22), 'playsound minecraft:block.stone.break hostile @a ~ ~ ~ 3 0.4'); fxShards(e, wsLocal(e, -2, 1, 22), 0.6, 18) }
      if (t == E.flare) {
        let q = wsLocal(e, 0, 58, 4)
        fxDust(e, q, WS_VIOLET, 2.2, 1.0, 60, 0.18); fxDust(e, q, WS_PALE, 1.2, 0.6, 30, 0.25); fxRunes(e, q, 2.5, 60)
        fxRing(e, 3.5, WS_DARK, 2.0, 36, 0.3)
        wsCmd(e, 'playsound minecraft:entity.warden.roar hostile @a ~ ~ ~ 4 0.6')
        wsHit(e, 6, -1, 0, 1.6, 0.4)
      }
      if (t >= E.length) { d.putBoolean('ws_awake', true); d.putBoolean('ws_guarded', false) }
    } else if (act == 'sweep') {
      // telegraph: he turns to the target and coils the blade back over his shoulder, trembling, before the whip
      if (t <= E.telegraph + 4 && target) wsAim(e, target)
      if (t == E.telegraph) sndWindup(e)
      if (t == E.sound_whoosh) sndSwing(e, 0.6)
      // trail along the blade's real arc (azimuth + = his left), only while the blade is moving fast
      let taz = E.trail_az || [-150, 110]
      if (t >= E.trail[0] && t <= E.trail[1]) fxBlade(e, taz[0] + (taz[1] - taz[0]) * (t - E.trail[0]) / (E.trail[1] - E.trail[0]), 44, 20, 80)
      if (t == E.impact) {
        sndImpact(e, 0.62)
        wsHit(e, 6.5, -0.75, 17, 1.7, 0.35)                              // the long arc reaches round to his flanks
        let f = wsFwd(e)
        wsCmd(e, `particle minecraft:sweep_attack ~${f[0] * 3} ~3 ~${f[1] * 3} 2 0.4 2 0 10 force`)
        fxCubes(e, wsLocal(e, 0, 40, 50), 1.5, 24)
      }
    } else if (act == 'push') {
      // telegraph: the claw is drawn back by his skull and fills with light; then a sudden thrust
      if (t <= E.impact - 2 && target) wsAim(e, target)
      if (t >= E.gather[0] && t <= E.gather[1] && t % 2 == 0) fxDust(e, wsLocal(e, 9, 52, 4), WS_VIOLET, 1.0, 0.15, 3, 0.02)
      if (t == E.telegraph) wsCmd(e, 'playsound minecraft:block.beacon.power_select hostile @a ~ ~ ~ 2 0.6')
      if (t == E.impact) {
        // a blocky shockwave: expanding square bursts and shards down a cone
        for (let i = 1; i <= 6; i++) {
          let q = wsLocal(e, 0, 44, 30 + i * 18)
          e.server.scheduleInTicks(i, () => { fxCubes(e, q, 0.3 + i * 0.25, 10 + i * 3); fxShards(e, q, 0.3 + i * 0.2, 4) })
        }
        wsCmd(e, 'playsound minecraft:entity.warden.sonic_boom hostile @a ~ ~ ~ 3 0.7'); sndImpact(e, 0.7, 2.2)
        wsHit(e, 9, 0.5, 7, 2.6, 0.55)
      }
    } else if (act == 'stomp') {
      // telegraph: the knee comes up high and HANGS (apex window) before the slam
      if (t == E.telegraph) wsCmd(e, 'playsound minecraft:block.anvil.place hostile @a ~ ~ ~ 2 0.4')
      if (t >= E.apex[0] && t <= E.apex[1] && t % 2 == 0) fxDust(e, wsLocal(e, -7, 18, 2), WS_DARK, 1.3, 0.3, 2, 0.01)
      if (t == E.impact) {
        wsCmd(e, 'playsound minecraft:entity.generic.explode hostile @a ~ ~ ~ 3 0.6'); sndImpact(e, 0.55, 3.0)
        let q = wsLocal(e, -7, 1, 2)
        fxShards(e, q, 1.2, 40); fxRing(e, 2.5, WS_DARK, 2.2, 28, 0.2); fxRing(e, 4.5, WS_VIOLET, 1.6, 40, 0.2)
        e.server.scheduleInTicks(3, () => fxRing(e, 5.5, WS_DARK, 1.8, 44, 0.2))
        wsQuake(e)
        wsHit(e, 5, -1, 15, 1.0, 0.9)
      }
    } else if (act == 'dash') {
      // telegraph: a long low crouch with the blade drawn in (0..roar); then the explosive lunge
      if (t <= E.roar && target) wsAim(e, target)
      if (t == E.roar) {                                                 // a short purple blink at the start
        fxDust(e, wsLocal(e, 0, 30, 0), WS_DARK, 2.0, 0.8, 30, 0.1); wsCmd(e, 'particle minecraft:reverse_portal ~ ~2 ~ 0.8 1.6 0.8 0.3 60 force')
        wsCmd(e, 'playsound minecraft:entity.enderman.teleport hostile @a ~ ~ ~ 2 0.5')
        wsCmd(e, 'playsound minecraft:entity.ravager.roar hostile @a ~ ~ ~ 3 0.7')
      }
      if (t >= E.lunge[0] && t <= E.lunge[1]) {
        let f = wsFwd(e)
        let vy = 0; try { let v = wsVec(e.getDeltaMovement()); if (v) vy = v.y } catch (err) {}
        e.setDeltaMovement(new $Vec3(f[0] * 1.3, vy, f[1] * 1.3)); e.hurtMarked = true
        fxDust(e, wsLocal(e, 0, 6, -10), WS_DARK, 1.8, 0.4, 4, 0.01)    // voxel trail behind him
        fxBlade(e, 0, 48, 30, 90)                                         // the extended blade leads the charge
        if (t == (E.thrust || 12)) sndSwing(e, 0.7)
        if (!d.getBoolean('ws_dash_hit') && wsHit(e, 4.5, 0.5, 18, 1.4, 0.4) > 0) { d.putBoolean('ws_dash_hit', true); sndImpact(e, 0.75, 2.2) }
      }
      if (t == E.brake) {                                                // brakes on planted feet, purple burst
        let f = wsFwd(e), vy = 0; try { let v = wsVec(e.getDeltaMovement()); if (v) vy = v.y } catch (err) {}
        e.setDeltaMovement(new $Vec3(f[0] * 0.1, vy, f[1] * 0.1)); e.hurtMarked = true
        fxCubes(e, wsLocal(e, 0, 20, 10), 1.0, 30); fxShards(e, wsLocal(e, 0, 1, 12), 1.0, 14)
        wsCmd(e, 'playsound minecraft:entity.iron_golem.damage hostile @a ~ ~ ~ 3 0.5')
      }
    } else if (act == 'summon_start') {
      if (t == 2) wsCmd(e, 'playsound minecraft:entity.evoker.prepare_summon hostile @a ~ ~ ~ 3 0.6')
      if (t == E.drive) { wsAt(e, wsLocal(e, -12, 1, 22), 'playsound minecraft:entity.generic.explode hostile @a ~ ~ ~ 2 0.5'); fxShards(e, wsLocal(e, -12, 1, 22), 0.8, 24) }
      if (t >= E.runes_from) {                                            // runes and cubes orbit the raised hand
        let h = wsLocal(e, 18, 74, 16), a = t * 0.5
        fxRunes(e, { x: h.x + Math.cos(a) * 1.0, y: h.y, z: h.z + Math.sin(a) * 1.0 }, 0.1, 3)
        fxDust(e, { x: h.x + Math.cos(a + 3) * 0.8, y: h.y + 0.2, z: h.z + Math.sin(a + 3) * 0.8 }, WS_VIOLET, 1.0, 0.05, 1, 0)
      }
      if (t == E.summon) {
        let tag = 'wsm_' + wsId(e), mobs = ['minecraft:wither_skeleton', 'minecraft:wither_skeleton', 'minecraft:skeleton']
        if (p2) mobs.push('minecraft:wither_skeleton')
        let pe = wsP(e)
        mobs.forEach((m, i) => {
          let a = (i / mobs.length) * WS_PI * 2, x = pe.x + Math.cos(a) * 6, z = pe.z + Math.sin(a) * 6
          e.server.runCommandSilent(`execute in ${e.level.dimension} run summon ${m} ${x} ${pe.y} ${z} {Tags:["${tag}","ws_minion"],PersistenceRequired:1b}`)
          fxCubes(e, { x: x, y: pe.y + 1, z: z }, 0.5, 20); fxRunes(e, { x: x, y: pe.y + 1, z: z }, 0.6, 20)
        })
        d.putBoolean('ws_guarded', true)
      }
      if (t >= E.length) { d.putString('ws_act', 'summon_hold'); d.putInt('ws_t', 0); wsTrigger(e, 'summon_loop') }
    } else if (act == 'summon_hold') {
      let h = wsLocal(e, 18, 74, 16), a = t * 0.35
      for (let k = 0; k < 2; k++) fxRunes(e, { x: h.x + Math.cos(a + k * WS_PI) * 1.2, y: h.y + Math.sin(a * 0.7) * 0.4, z: h.z + Math.sin(a + k * WS_PI) * 1.2 }, 0.05, 2)
      if (t % 4 == 0) fxDust(e, { x: h.x + Math.cos(-a) * 0.9, y: h.y, z: h.z + Math.sin(-a) * 0.9 }, WS_DARK, 1.3, 0.05, 2, 0)
      if (t % 10 == 0 && wsMinionsAlive(e) == 0) { d.putBoolean('ws_guarded', false); wsStart(e, 'summon_end'); d.putInt('cd_summon', 900) }
    } else if (act == 'summon_end') {
      if (t == E.release) {                                               // the gathered energy is flung away
        let h = wsLocal(e, 22, 50, 18)
        fxDust(e, h, WS_VIOLET, 1.8, 0.8, 40, 0.25); fxRunes(e, h, 1.5, 40)
        wsCmd(e, 'playsound minecraft:entity.illusioner.cast_spell hostile @a ~ ~ ~ 3 0.6')
      }
    }
    // hold the aimed facing through the swing so the body AI can't turn him away mid-attack
    if (d.contains('ws_lock')) { let ly = d.getFloat('ws_lock'), off = ((wsYaw(e) - ly) % 360 + 540) % 360 - 180; if (Math.abs(off) > 1) wsSetYaw(e, ly) }
    let len = act == 'summon_hold' ? 0 : E.length
    if (len && t >= len && act != 'summon_start') { d.putString('ws_act', ''); d.putBoolean('ws_dash_hit', false); d.remove('ws_lock') }
    return
  }

  // ---- choosing the next move
  if (!target || !target.isAlive()) { e.getNavigation().stop(); return }
  let dist = wsDist(e, target), r = Math.random()
  if (d.getInt('cd_summon') == 0 && e.getHealth() < e.getMaxHealth() * 0.8 && dist < 24) { wsStart(e, 'summon_start'); return }
  if (p2 && d.getInt('cd_stomp') == 0 && dist < 5.5) { wsStart(e, 'stomp'); d.putInt('cd_stomp', 160); return }
  if (p2 && d.getInt('cd_dash') == 0 && dist > 8 && dist < 20 && r < 0.05) { wsStart(e, 'dash'); d.putInt('cd_dash', 300); return }
  if (d.getInt('cd_push') == 0 && dist < 7 && r < 0.35) { wsStart(e, 'push'); d.putInt('cd_push', 200); return }
  if (d.getInt('cd_sweep') == 0 && dist < 6.2) { wsStart(e, 'sweep'); d.putInt('cd_sweep', 50); return }
  if (dist > 5.0) e.getNavigation().moveTo(target, 1.0)
  else { e.getNavigation().stop(); wsFace(e, target) }
}
