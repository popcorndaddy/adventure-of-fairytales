"""Writes kubejs/startup_scripts/bosses/withered_king_data.js from the Blender bake: per-action event times, 20 Hz world
probes (blade grip/tip, left palm, feet; model pixels, 8 px = 1 block, +x = his right, -z = his front) and the dash
root-motion table that the animation's planted feet were authored against."""
import json, math, sys
B = json.load(open(sys.argv[1])); out = sys.argv[2]
def smooth(u): u = max(0.0, min(1.0, u)); return u * u * (3 - 2 * u)
def dash_speed(t, s=0.9, e=1.5, vm=128.0):
    if t < s or t > e: return 0.0
    u = (t - s) / (e - s)
    return vm * (smooth(u / 0.25) if u < 0.25 else (1.0 if u < 0.78 else 1 - smooth((u - 0.78) / 0.22) * 0.55))
D = {}
for name, a in B.items():
    short = name.replace('withered_king_', '')
    pr = a['probes']
    D[short] = dict(len=a['length'], loop=a['loop'], ev=[[e['t'], e['kind']] + ([e['side']] if 'side' in e else []) for e in a['events']],
                    grip=[p['grip'] for p in pr], tip=[p['tip'] for p in pr], palm=[p['palm_l'] for p in pr],
                    footL=[p['foot_l'] for p in pr], footR=[p['foot_r'] for p in pr])
# per-tick dash displacement (blocks) for animation time [k/20, (k+1)/20)
dash = []
for k in range(int(round(2.5 * 20))):
    s = 0.0
    for i in range(20): s += dash_speed((k + (i + 0.5) / 20) / 20) / 20 / 20
    dash.append(round(s / 8.0, 4))
D['dash']['move'] = dash
js = ('// Generated by make_js_data.py from the Blender bake - do not edit by hand.\n'
      '// Probes are model pixels (8 px = 1 block): x = his right, y = up, z = his back (-z is in front of him). 20 samples per second.\n'
      'global.WK_DATA = ' + json.dumps(D, separators=(',', ':')) + '\n')
open(out, 'w').write(js)
print('dash distance blocks', round(sum(dash), 2), 'bytes', len(js))
